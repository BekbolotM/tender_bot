/**
 * Проверки и тексты доступа к админке: что считать идентификатором, кого
 * нельзя удалять и что отвечать постороннему. Живут отдельно от index.ts,
 * потому что тот тянет grammy и базу, а здесь только чистые функции —
 * их и проверяют тесты, не поднимая ни бота, ни БД.
 */

/** Длина текста в answerCallbackQuery у Telegram — не больше 200 символов. */
export const CALLBACK_ALERT_MAX = 200;

/**
 * Telegram ID — только голое число. Раньше из строки вычёркивались все нецифры,
 * и вставленная в чат ссылка-приглашение превращалась в «админа 38»: такая
 * строка потом молча ломала каждую рассылку крона. 15 цифр — потолок: длиннее
 * уже не помещается в точное целое, а id в Telegram короче.
 */
const ADMIN_ID = /^\d{5,15}$/;

export function parseAdminId(input: string): number | null {
  const trimmed = input.trim();
  if (!ADMIN_ID.test(trimmed)) return null;
  const id = Number(trimmed);
  return Number.isSafeInteger(id) && id > 0 ? id : null;
}

/**
 * Почему удаление админа отклонено — или null, если можно.
 * Себя не удаляем: доступ пропадает мгновенно, а вернуть его уже некому.
 * Последнего админа не удаляем, когда владелец не задан в env: на пустой
 * таблице admins снова срабатывает захват бота (claimOwnership), и права
 * достаются первому постороннему, который напишет боту.
 */
export function adminDeletionError(
  target: number,
  actor: number,
  admins: number[],
  owners: number[],
): string | null {
  if (target === actor) return "Себя удалить нельзя — попросите об этом другого админа.";
  if (owners.length === 0 && !admins.some((id) => id !== target)) {
    return (
      "Нельзя удалить последнего админа: бота заберёт первый написавший посторонний. " +
      "Сначала добавьте второго админа или задайте OWNER_TELEGRAM_ID."
    );
  }
  return null;
}

/**
 * Отказ постороннему. Две формы одного текста: в чат уходит HTML (id в
 * <code> — его удобно скопировать и переслать админу), а в всплывающий
 * ответ на кнопку разметку класть нельзя, там текст показывается как есть.
 */
export function accessDeniedText(
  tgId: number,
  hasToken: boolean,
  ttlHours: number,
): { plain: string; html: string } {
  // «Не существует», «уже использована» и «просрочена» отвечают одинаково:
  // по разнице ответов чужие ссылки можно было бы перебирать.
  const build = (id: string) =>
    hasToken
      ? `Ссылка не сработала: приглашение одноразовое и живёт ${ttlHours} ч.\n` +
        `Попросите новую ссылку или пусть админ добавит вас по id: ${id}`
      : `Доступ только для админов.\nВаш Telegram ID: ${id}`;

  return { plain: build(String(tgId)), html: build(`<code>${tgId}</code>`) };
}

/**
 * Итог отзыва ссылок. Про чужие говорим прямо: кнопка гасит все приглашения
 * сразу, и нажавший должен понимать, что оборвал и чью-то уже разосланную ссылку.
 */
export function revokeNote(revoked: number, byOthers: number): string {
  if (revoked <= 0) return "Отзывать было нечего — действующих ссылок нет.";
  // Чужие ссылки считаются отдельным запросом до отзыва, поэтому их могло
  // стать меньше: «из 2 отозванных 3 чужие» выглядело бы сбоем.
  const others = Math.min(byOthers, revoked);
  const tail = others > 0 ? ` Из них выпущено другими админами: ${others}.` : "";
  return `❌ Отозвано ссылок: ${revoked}.${tail}`;
}

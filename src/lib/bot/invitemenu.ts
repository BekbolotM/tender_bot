/**
 * Текст и кнопки приглашений для меню «Админы». Живут отдельно от menus.ts,
 * потому что тот тянет grammy и разметку сообщений, а здесь только строки —
 * их и проверяют тесты, не поднимая ни бота, ни базу.
 */

export type MenuButton = { text: string; data: string };

/** Пояснение под списком админов: чем ссылка отличается от добавления по id. */
export function inviteHint(activeInvites: number, ttlHours: number): string {
  return [
    `🔗 Ссылка-приглашение одноразовая и действует ${ttlHours} ч.: перешедший по ней сразу становится админом.`,
    // Права у приглашённого те же, что у пригласившего: без этой строки
    // ссылку пересылают как «доступ посмотреть», а она отдаёт и управление админами.
    "Он получит те же права, что и вы, включая удаление других админов.",
    activeInvites > 0
      ? `Сейчас действует ссылок: ${activeInvites}. Показать их заново нельзя — только отозвать и выпустить новую.`
      : "Действующих ссылок нет.",
    // Про «все» и «чужие» говорим заранее: кнопка отзыва одна на бота.
    "❌ Отзыв гасит сразу все действующие ссылки, включая выпущенные другими админами.",
    "Удаление админа гасит и его невыданные ссылки.",
  ].join("\n");
}

/**
 * Отзыв показываем, только когда есть что отзывать: кнопка «отозвать 0 ссылок»
 * ничего не меняет, но выглядит рабочей — и её приходится нажимать, чтобы понять.
 */
export function inviteButtons(activeInvites: number): MenuButton[] {
  const buttons: MenuButton[] = [{ text: "🔗 Пригласить по ссылке", data: "admin_invite" }];
  if (activeInvites > 0) {
    buttons.push({ text: `❌ Отозвать ссылки (${activeInvites})`, data: "admin_revoke" });
  }
  return buttons;
}

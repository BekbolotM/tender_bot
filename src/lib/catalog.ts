/**
 * Готовая площадка: адрес списка и правила разбора, подобранные и проверенные
 * заранее. Нужна ради нетехнического человека — вместо того чтобы искать ссылку
 * и объяснять боту вёрстку, он выбирает площадку из списка одной кнопкой.
 */
export type CatalogEntry = {
  /** Короткий идентификатор, уходит в callback_data кнопки. Менять нельзя: он в кнопках. */
  id: string;
  /** Название для человека — как площадка подписана в меню. */
  title: string;
  /** Страна: по ней каталог группируется, местные площадки идут первыми. */
  country: string;
  listUrl: string;
  selectors: Selectors;
  /** Поиск на стороне площадки, если она умеет искать по словам обычной ссылкой. */
  search?: SiteSearch;
  /**
   * Пауза между запросами, которую площадка просит соблюдать (robots.txt).
   * Пусто — площадка ни о чём не просила, хватает обычной вежливости.
   */
  crawlDelayMs?: number;
  /** Что человеку полезно знать про эту площадку до того, как он её добавит. */
  note?: string;
};


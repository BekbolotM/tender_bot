/** Насколько поздно страна показывается в меню. Неизвестная — в самом конце. */
function countryRank(country: string): number {
  const index = COUNTRY_ORDER.indexOf(country);
  return index === -1 ? COUNTRY_ORDER.length : index;
}

/**
 * Площадки в порядке показа: сначала кыргызские, потом соседи. Сортировка
 * устойчивая, поэтому внутри страны сохраняется порядок из `CATALOG`.
 * Копию возвращаем намеренно: меню не должно уметь переставить сам каталог.
 */
export function catalogList(): CatalogEntry[] {
  return [...CATALOG].sort((a, b) => countryRank(a.country) - countryRank(b.country));
}

/**
 * Площадка по идентификатору из кнопки. Кнопка могла остаться в старом
 * сообщении от прошлой версии бота, поэтому неизвестный id — это не сбой,
 * а обычный «ничего не нашлось».
 */
export function catalogEntry(id: string): CatalogEntry | undefined {
  return CATALOG.find((entry) => entry.id === id);
}
